// Preset palettes for when dynamic color is off or unavailable (Android < 12).
//
// Generated, not hand-picked: each pair is Material's tonal-spot scheme (the default Material You
// variant on Android 12-14) for the seed in ThemeAccent, contrast level 0, produced with
// @material/material-color-utilities 0.3.0:
//
//   new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), isDark, 0.0)
//
// so tone pairs keep the M3 contrast guarantees (checked by AccentColorSchemeTest).
// To add a preset, add a seed to ThemeAccent, generate both schemes the same way and map them in
// accentColorScheme().

/** The fallback scheme for [accent]; dynamic color, when on, replaces it entirely. */
fun accentColorScheme(accent: ThemeAccent, dark: Boolean): ColorScheme = when (accent) {
    ThemeAccent.TEAL -> if (dark) TealDark else TealLight
    ThemeAccent.BLUE -> if (dark) BlueDark else BlueLight
    ThemeAccent.VIOLET -> if (dark) VioletDark else VioletLight
    ThemeAccent.ROSE -> if (dark) RoseDark else RoseLight
    ThemeAccent.AMBER -> if (dark) AmberDark else AmberLight
    ThemeAccent.GREEN -> if (dark) GreenDark else GreenLight
}

